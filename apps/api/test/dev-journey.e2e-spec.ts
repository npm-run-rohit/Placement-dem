import { Channel, INDUSTRY_TYPES_SEED, OutcomeType, Stage } from '@bimaplacement/contracts';
import { DataSource } from 'typeorm';
import { MailOutboundHandler } from '../src/modules/communications/mail-outbound.handler';
import { CopycatRunnerHandler } from '../src/integrations/copycat/copycat-runner.handler';
import { TEST_USERS, TestApp, as, createTestApp } from './helpers/app';

/** Journey simulator (dev, demo 2026-11-05): one step at a time through the real services, intake to close. */
describe('Dev journey simulator', () => {
  let t: TestApp;
  let ds: DataSource;
  let pm: ReturnType<typeof as>;

  /** What the worker does for mail: relay each mail outbox row of the ticket to the mail handler. */
  const deliverMail = async (ticketId: string) => {
    const rows: Array<{
      id: string;
      event_type: string;
      aggregate_id: string;
      created_at: Date;
      payload: Record<string, unknown>;
    }> = await ds.query(
      `SELECT id, event_type, aggregate_id, created_at, payload FROM outbox_events WHERE destination = 'mail' AND aggregate_id = $1 ORDER BY created_at`,
      [ticketId],
    );
    for (const r of rows)
      await t.app.get(MailOutboundHandler).handle(r.event_type, {
        outboxId: r.id,
        eventType: r.event_type,
        aggregateId: r.aggregate_id,
        occurredAt: r.created_at.toISOString(),
        ...r.payload,
      });
  };

  beforeAll(async () => {
    t = await createTestApp();
    ds = t.app.get(DataSource);
    pm = as(t, TEST_USERS.pm);
    // E2E FIXTURE - mock RM and three insurers with an EB contact each (not PRD data)
    await ds.query(
      `INSERT INTO users (sahayak_user_id, email, name, roles, row_version) VALUES ('dev:rm.journey.e2e@bimakavach.test', 'rm.journey.e2e@bimakavach.test', 'E2E RM Journey', '{rm}', 1)`,
    );
    for (const n of [1, 2, 3]) {
      const [{ id: insurerId }] = await ds.query(
        `INSERT INTO insurers (code, name, status, row_version) VALUES ($1, $2, 'Active', 1) RETURNING id`,
        [`e2e-journey-${n}`, `E2E Journey Insurer ${n}`],
      );
      const [{ id: branchId }] = await ds.query(
        `INSERT INTO insurer_branches (insurer_id, name, status, row_version) VALUES ($1, 'E2E Branch', 'Active', 1) RETURNING id`,
        [insurerId],
      );
      await ds.query(
        `INSERT INTO insurer_pocs (branch_id, product_group, name, email, row_version) VALUES ($1, 'EB', $2, $3, 1)`,
        [branchId, `Journey POC ${n}`, `poc${n}@journey-insurer.example.test`],
      );
    }
  });

  afterAll(async () => {
    await t?.app.close();
  });

  it('runs a manual ticket to QCR released, mailing the float and the QCR to the RM', async () => {
    const res = await pm.post('/dev/simulate/journey', { channel: 'manual' }).expect(201);
    const { ticketId, steps } = res.body as {
      ticketId: string;
      steps: Array<{ step: string; stage: string }>;
    };
    expect(steps.at(-1)?.stage).toBe(Stage.QCR_RELEASED);
    expect(steps.map((s) => s.step)).toEqual(
      expect.arrayContaining([
        'RFQ validated',
        expect.stringMatching(/^RFQ floated to 3 insurer/),
        expect.stringMatching(/^Insurer quote received from /),
        expect.stringMatching(/generated by Copycat$/),
        expect.stringMatching(/sent to the RM by mail$/),
      ]),
    );
    const ticket = (await pm.get(`/tickets/${ticketId}`).expect(200)).body;
    expect(ticket).toMatchObject({ channel: Channel.MANUAL, stage: Stage.QCR_RELEASED });

    await deliverMail(ticketId);
    const mails: Array<{ template_id: string | null; direction: string }> = await ds.query(
      `SELECT template_id, direction FROM mail_messages WHERE ticket_id = $1`,
      [ticketId],
    );
    expect(mails.filter((m) => m.template_id === 'INS-T01')).toHaveLength(3);
    expect(mails.filter((m) => m.direction === 'inbound')).toHaveLength(3); // the three insurer replies
    const [{ n: qcrMail }] = await ds.query(
      `SELECT count(*)::int AS n FROM outbox_events WHERE aggregate_id = $1 AND event_type = 'mail.qcr_to_rm'`,
      [ticketId],
    );
    expect(qcrMail).toBe(1);
    const toRm: Array<{ to_addresses: string[] }> = await ds.query(
      `SELECT to_addresses FROM mail_messages WHERE ticket_id = $1 AND thread_id IS NULL AND direction = 'outbound'`,
      [ticketId],
    );
    expect(toRm.length).toBeGreaterThanOrEqual(1);

    // then on to the client decision
    const closed = await pm.post(`/dev/tickets/${ticketId}/simulate/run`, { until: 'closed' }).expect(201);
    expect(closed.body.steps).toHaveLength(1);
    const after = (await pm.get(`/tickets/${ticketId}`).expect(200)).body;
    expect(after).toMatchObject({ stage: Stage.CLOSED, outcome: OutcomeType.QUOTE_SELECTED });
  });

  it('says it is done on a closed ticket and changes nothing', async () => {
    const { ticketId } = (
      await pm.post('/dev/simulate/journey', { channel: 'manual', until: 'closed' }).expect(201)
    ).body;
    const [{ n: before }] = await ds.query(
      `SELECT count(*)::int AS n FROM audit_events WHERE ticket_id = $1`,
      [ticketId],
    );
    const res = await pm.post(`/dev/tickets/${ticketId}/simulate/next`).expect(201);
    expect(res.body).toMatchObject({ done: true, stage: Stage.CLOSED });
    const [{ n: after }] = await ds.query(
      `SELECT count(*)::int AS n FROM audit_events WHERE ticket_id = $1`,
      [ticketId],
    );
    expect(after).toBe(before);
  });

  it('runs a BimaSetu float to close through the BimaSetu inbound path', async () => {
    const head = as(t, TEST_USERS.head);
    const res = await head
      .post('/dev/simulate/journey', { channel: 'bimasetu', until: 'closed' })
      .expect(201);
    const steps = res.body.steps as Array<{ step: string; stage: string }>;
    expect(steps.map((s) => s.step)).toEqual(
      expect.arrayContaining([
        expect.stringMatching(/sent to BimaSetu$/),
        expect.stringMatching(/^Client confirmed .* in BimaSetu$/),
      ]),
    );
    const ticket = (await head.get(`/tickets/${res.body.ticketId}`).expect(200)).body;
    expect(ticket).toMatchObject({
      channel: Channel.BIMASETU,
      stage: Stage.CLOSED,
      outcome: OutcomeType.QUOTE_SELECTED,
    });
    const [{ n }] = await ds.query(
      `SELECT count(*)::int AS n FROM outbox_events WHERE aggregate_id = $1 AND event_type = 'qcr_round'`,
      [res.body.ticketId],
    );
    expect(n).toBe(1);
  });

  it('has the RM answer an open query before validating, one step at a time', async () => {
    const [{ id: rmUserId }] = await ds.query(
      `SELECT id FROM users WHERE email = 'rm.journey.e2e@bimakavach.test'`,
    );
    const ticketId = (
      await pm
        .post('/tickets', {
          rfqLinkUrl: 'https://example.test/rfq/e2e-journey',
          businessName: 'E2E Journey Queries Pvt Ltd',
          industryType: INDUSTRY_TYPES_SEED[0],
          productType: 'GMC',
          businessType: 'New',
          rmUserId,
        })
        .expect(201)
    ).body.id;
    const next = async () => (await pm.post(`/dev/tickets/${ticketId}/simulate/next`).expect(201)).body;
    expect((await next()).step).toBe('Risk tier set to Preferred');
    await pm.post(`/tickets/${ticketId}/rfq/queries`, { newQueries: ['Employee census'] }).expect(201);
    expect(await next()).toMatchObject({ step: 'RM answered 1 query(ies)', stage: Stage.RFQ_REVIEW });
    expect(await next()).toMatchObject({ step: '1 RM answer(s) resolved', stage: Stage.RFQ_REVIEW });
    expect(await next()).toMatchObject({ step: 'RFQ validated', stage: Stage.INSURER_SELECTION });
  });

  it('applies a Copycat answer once: a second run of the same request (worker + dev run) keeps the checked rows', async () => {
    const [{ id: rmUserId }] = await ds.query(
      `SELECT id FROM users WHERE email = 'rm.journey.e2e@bimakavach.test'`,
    );
    // a fresh ticket stopped at the generated draft: step until Copycat has answered
    const id = (
      await pm
        .post('/tickets', {
          rfqLinkUrl: 'https://example.test/rfq/e2e-journey-copycat',
          businessName: 'E2E Journey Copycat Pvt Ltd',
          industryType: INDUSTRY_TYPES_SEED[0],
          productType: 'GMC',
          businessType: 'New',
          rmUserId,
        })
        .expect(201)
    ).body.id;
    for (let i = 0; i < 20; i++) {
      const r = (await pm.post(`/dev/tickets/${id}/simulate/next`).expect(201)).body;
      if (/generated by Copycat$/.test(r.step)) break;
    }
    const [draft] = (await pm.get(`/tickets/${id}/qcrs`).expect(200)).body;
    expect(draft).toMatchObject({ status: 'draft', copycatStatus: 'ready' });
    await pm.put(`/tickets/${id}/qcrs/${draft.id}/rows-checked`, { checked: true }).expect(200);
    await t.app.get(CopycatRunnerHandler).handle('copycat.generate', { requestId: draft.copycatRequestId });
    const [again] = (await pm.get(`/tickets/${id}/qcrs`).expect(200)).body;
    expect(again.rowsChecked).toBe(true);
  });

  it('skips a quote it cannot mark usable (open clarification) instead of getting stuck', async () => {
    const [{ id: rmUserId }] = await ds.query(
      `SELECT id FROM users WHERE email = 'rm.journey.e2e@bimakavach.test'`,
    );
    const id = (
      await pm
        .post('/tickets', {
          rfqLinkUrl: 'https://example.test/rfq/e2e-journey-clar',
          businessName: 'E2E Journey Clarification Pvt Ltd',
          industryType: INDUSTRY_TYPES_SEED[0],
          productType: 'GMC',
          businessType: 'New',
          rmUserId,
        })
        .expect(201)
    ).body.id;
    const next = async () => (await pm.post(`/dev/tickets/${id}/simulate/next`).expect(201)).body;
    for (let i = 0; i < 3; i++) await next(); // risk tier, validate, float
    const [th1, th2] = (await pm.get(`/tickets/${id}/threads`).expect(200)).body;
    // TH-01 quotes, then the insurer asks a question on the same thread: that quote is not decidable
    await pm.post(`/dev/tickets/${id}/threads/${th1.id}/insurer`, { kind: 'quote' }).expect(201);
    await pm
      .post(`/dev/tickets/${id}/threads/${th1.id}/insurer`, { kind: 'clarification', text: 'Need census' })
      .expect(201);
    const step = await next();
    expect(step.step).toMatch(/^Insurer quote received from /); // moved on to another thread
    expect(step.detail).toContain(th2.threadRef);
    const after = await next();
    expect(after.step).toMatch(/marked usable$/);
    const quotes = (await pm.get(`/tickets/${id}/quotes`).expect(200)).body as Array<{
      threadId: string;
      decision: string | null;
    }>;
    expect(quotes.find((q) => q.threadId === th1.id)?.decision).toBeNull();
    expect(quotes.find((q) => q.threadId === th2.id)?.decision).toBe('usable');
  });

  it('refuses with a reason when no insurer has a contact for the product group', async () => {
    const [{ id: rmUserId }] = await ds.query(
      `SELECT id FROM users WHERE email = 'rm.journey.e2e@bimakavach.test'`,
    );
    const ticketId = (
      await pm
        .post('/tickets', {
          rfqLinkUrl: 'https://example.test/rfq/e2e-journey-cgl',
          businessName: 'E2E Journey No Contacts Pvt Ltd',
          industryType: INDUSTRY_TYPES_SEED[0],
          productType: 'CGL',
          businessType: 'New',
          rmUserId,
        })
        .expect(201)
    ).body.id;
    // CGL is in the Liability group: retire every active Liability contact for this test (e2e DB only), restore after
    const retired: Array<{ id: string }> = await ds.query(
      `UPDATE insurer_pocs SET active = false WHERE product_group = 'Liability' AND active RETURNING id`,
    );
    let res;
    try {
      res = await pm.post(`/dev/tickets/${ticketId}/simulate/run`, {}).expect(422);
    } finally {
      if (retired.length)
        await ds.query(`UPDATE insurer_pocs SET active = true WHERE id = ANY($1)`, [
          retired.map((r) => r.id),
        ]);
    }
    expect(res.body.message).toMatch(/No eligible insurers with contacts for CGL/);
  });
});
